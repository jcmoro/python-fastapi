from __future__ import annotations

from pydantic import BaseModel, ConfigDict, Field

from contexts.assistant.application.dtos import AnswerDTO


class AskRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    question: str = Field(
        ...,
        min_length=1,
        max_length=1000,
        description="Natural-language question about the catalog.",
        examples=["Which widgets cost less than 20 EUR?"],
    )


class UsageResponse(BaseModel):
    model: str = Field(..., description="Model that produced the answer.")
    input_tokens: int = Field(..., description="Input tokens billed for the completion.")
    output_tokens: int = Field(..., description="Output tokens billed for the completion.")
    latency_ms: int = Field(..., description="Wall-clock latency of the LLM call in ms.")


class AnswerResponse(BaseModel):
    text: str = Field(..., description="Answer generated by the assistant.")
    usage: UsageResponse

    @classmethod
    def from_dto(cls, dto: AnswerDTO) -> AnswerResponse:
        return cls(
            text=dto.text,
            usage=UsageResponse(
                model=dto.usage.model,
                input_tokens=dto.usage.input_tokens,
                output_tokens=dto.usage.output_tokens,
                latency_ms=dto.usage.latency_ms,
            ),
        )
