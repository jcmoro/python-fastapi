from __future__ import annotations

from typing import Literal
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, model_validator

from contexts.assistant.application.dtos import (
    AnswerDTO,
    RecommendationSummaryDTO,
    SourceDTO,
    UsageDTO,
)


class AskRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    question: str = Field(
        ...,
        min_length=1,
        max_length=1000,
        description="Natural-language question about the catalog.",
        examples=["Which widgets cost less than 20 EUR?"],
    )


class UsageResponse(BaseModel):
    model: str = Field(..., description="Model that produced the answer.")
    input_tokens: int = Field(..., description="Input tokens billed for the completion.")
    output_tokens: int = Field(..., description="Output tokens billed for the completion.")
    latency_ms: int = Field(..., description="Wall-clock latency of the LLM call in ms.")

    @classmethod
    def from_dto(cls, dto: UsageDTO) -> UsageResponse:
        return cls(
            model=dto.model,
            input_tokens=dto.input_tokens,
            output_tokens=dto.output_tokens,
            latency_ms=dto.latency_ms,
        )


class SourceResponse(BaseModel):
    product_id: UUID = Field(..., description="Catalog product the document was built from.")
    content: str = Field(..., description="Indexed text of the product.")
    score: float = Field(..., description="Cosine similarity to the question (higher is closer).")

    @classmethod
    def from_dto(cls, dto: SourceDTO) -> SourceResponse:
        return cls(product_id=dto.product_id, content=dto.content, score=dto.score)


class RecommendationResponse(BaseModel):
    product_id: UUID | None = Field(
        ..., description="Recommended catalog product. Null unless reason is 'chosen'."
    )
    sku: str | None = Field(..., description="SKU of the recommended product, or null.")
    score: float | None = Field(
        ..., description="Probability that it suits the asked use (0-1), or null."
    )
    reason: Literal["chosen", "below_threshold", "no_assessments"] = Field(
        ...,
        description="Outcome of the candidate selector: 'chosen' (a product is recommended), "
        "'below_threshold' (no candidate was good enough) or 'no_assessments' (no candidate "
        "could be assessed).",
    )

    @model_validator(mode="after")
    def _product_fields_only_when_chosen(self) -> RecommendationResponse:
        filled = [self.product_id is not None, self.sku is not None, self.score is not None]
        if self.reason == "chosen" and not all(filled):
            raise ValueError("product_id, sku and score are required when reason is 'chosen'")
        if self.reason != "chosen" and any(filled):
            raise ValueError("product_id, sku and score must be null unless reason is 'chosen'")
        return self

    @classmethod
    def from_dto(cls, dto: RecommendationSummaryDTO) -> RecommendationResponse:
        return cls(
            product_id=dto.product_id, sku=dto.sku, score=dto.score, reason=dto.reason.value
        )


class AnswerResponse(BaseModel):
    text: str = Field(..., description="Answer generated by the assistant, or the fallback text.")
    sources: list[SourceResponse] = Field(
        ..., description="Catalog products retrieved for the question, most similar first."
    )
    fallback_used: bool = Field(
        ...,
        description="True when the LLM was unavailable and the answer lists the retrieved "
        "products without generation.",
    )
    usage: UsageResponse | None = Field(
        ..., description="LLM usage. Null when the fallback was used (no LLM call succeeded)."
    )
    recommendation: RecommendationResponse | None = Field(
        default=None,
        description="Result of the candidate selector. Null when the selector did not run "
        "(rag mode, or the agent answered without recommending).",
    )

    @classmethod
    def from_dto(cls, dto: AnswerDTO) -> AnswerResponse:
        return cls(
            text=dto.text,
            sources=[SourceResponse.from_dto(source) for source in dto.sources],
            fallback_used=dto.fallback_used,
            usage=UsageResponse.from_dto(dto.usage) if dto.usage is not None else None,
            recommendation=(
                RecommendationResponse.from_dto(dto.recommendation)
                if dto.recommendation is not None
                else None
            ),
        )
